rows = []
for name, lang, slug, action, note in MAP:
    c = CLUSTERS.get((name, lang))
    if not c:
        continue
    rows.append((c["vol"], name, lang, slug, action, c["n"], c["top"][:6], note))
rows.sort(reverse=True)

new = sum(1 for r in rows if r[4] == "создать")
edit = sum(1 for r in rows if r[4] == "ПРАВИТЬ")
total = sum(r[0] for r in rows)


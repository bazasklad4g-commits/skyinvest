#!/usr/bin/env python
"""Итоговый план: кластер -> конкретная страница и действие."""
import io, re

CLUSTERS = {}
cur = None
for line in io.open("data/ads/CLUSTERS.md", encoding="utf-8"):
    m = re.match(r"^## (.+?) \((\w+)\) — (\d+)/мес, (\d+) запросов", line)
    if m:
        cur = (m.group(1), m.group(2))
        CLUSTERS[cur] = {"vol": int(m.group(3)), "n": int(m.group(4)), "top": []}
    elif cur and line.startswith("- "):
        CLUSTERS[cur]["top"].append(line[2:].rsplit(" — ", 1)[0].strip())

# кластер -> (slug, действие, комментарий)
